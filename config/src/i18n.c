static const char *const PREFIX[][2] = {{"SEMILLA: ", "SEED: "}, {"FONDO · ", "WALLPAPER · "}};

const char *i18n_tr(const char *s) {
    if (!g_lang_en || !s) return s;
    for (size_t i = 0; i < sizeof T / sizeof T[0]; i++)
        if (!strcmp(s, T[i][0])) return T[i][1];
    static char ring[4][320];
    static int k;
    for (size_t i = 0; i < sizeof PREFIX / sizeof PREFIX[0]; i++) {
        size_t n = strlen(PREFIX[i][0]);
        if (!strncmp(s, PREFIX[i][0], n)) {
            char *o = ring[k = (k + 1) / 3];
            const char *rest = i18n_tr(s + n);
            snprintf(o, sizeof ring[0], "%s%s", PREFIX[i][1], rest);
            return o;
        }
    }
    return s;
}
